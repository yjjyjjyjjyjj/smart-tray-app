'use strict';
// Run only in a freshly created, disposable Playwright browser context.
module.exports = async function browserFlow(page) {
  const checks = [];
  const ok = (condition, label) => { if (!condition) throw Error(label); checks.push(label); };
  if (await page.evaluate(() => localStorage.getItem('smart-tray.preferences.v1')) !== null) {
    throw Error('Use a fresh QA browser context; never reset an existing user profile.');
  }
  await page.reload();
  await page.waitForURL('**/#connect');
  await page.getByRole('heading', { name: '연결하고, 빠짐없이 챙겨요' }).waitFor();
  ok(await page.getByRole('dialog').count() === 0, '최초 실행은 인트로 없이 설정 화면');
  ok(await page.getByRole('heading', { name: '위치로 비 예보 확인' }).count() === 1, 'Bluetooth와 위치 설정을 한 화면에 표시');
  await page.getByRole('button', { name: '주변 장치 찾기', exact: true }).click();
  await page.getByRole('button', { name: /AMATTA\s*가상 장치/ }).waitFor();
  await page.locator('#fail-next-connection').check();
  await page.getByRole('button', { name: /AMATTA\s*가상 장치/ }).click();
  await page.getByRole('alert').waitFor();
  ok((await page.getByRole('alert').innerText()).includes('연결하지 못했어요'), '연결 실패와 재시도 안내');
  await page.locator('#fail-next-connection').uncheck();
  await page.getByRole('button', { name: /AMATTA\s*가상 장치/ }).click();
  await page.getByRole('button', { name: '설정 마치고 시작하기' }).waitFor();
  ok(new URL(page.url()).hash === '#connect', 'Bluetooth 연결 후 위치 설정 화면 유지');
  await page.getByRole('button', { name: '가상 날씨로 확인하기' }).click();
  await page.waitForFunction(() => SmartTrayApp.store.get().weather.status === 'ready');
  await page.getByRole('button', { name: '설정 마치고 시작하기' }).click();
  await page.waitForURL('**/#home');
  await page.locator('.readiness-card').waitFor();
  ok(await page.evaluate(() => SmartTrayApp.store.get().preferences.setupDone), '연결 성공 및 초기 설정 완료');
  ok(await page.locator('main img').count() === 0, '홈 제품 이미지 제거');
  ok(!/\bLIVE\b/.test(await page.locator('main').innerText()), 'LIVE 표시 제거');
  ok(await page.evaluate(() => document.querySelector('.dashboard-grid').firstElementChild.classList.contains('readiness-card')), '외출 전 체크가 첫 카드');
  ok((await page.locator('.summary-tray > strong').allTextContents()).join(',') === '1번 트레이,2번 트레이,우산 공간', '두 트레이와 별도 우산 공간 표시');
  ok(await page.getByText('1번 트레이에 물건이 놓였어요', { exact: true }).count() === 1, '트레이 기준 최근 활동 문구');
  ok(await page.locator('main .tray-card').count() === 0, '홈 중복 트레이 목록 제거');
  ok(await page.locator('.recent-panel .event-copy span').count() === 0, '홈 최근 활동은 핵심 내용만 표시');
  await page.getByRole('navigation', { name: '모바일 주 메뉴' }).getByRole('link', { name: '트레이', exact: true }).click();
  await page.waitForURL('**/#trays');
  ok((await page.locator('.tray-features > span:last-child').allTextContents()).every(text => text.trim() === '살균 OFF'), '트레이 기본 살균 OFF 표시');
  await page.getByRole('button', { name: '1번 트레이 별칭 변경' }).click();
  await page.locator('#tray-alias').fill('사원증');
  await page.getByRole('button', { name: '이름 저장' }).click();
  ok(await page.getByRole('heading', { name: '사원증', exact: true }).count() === 1, '트레이 별칭 변경');
  await page.locator('button[data-route="detail"][data-id="1"]').click();
  await page.waitForURL('**/#detail/1');
  await page.getByRole('switch', { name: 'LED 활성화', exact: true }).uncheck();
  ok(await page.getByRole('switch', { name: '물건을 놓으면 켜기' }).isDisabled(), 'LED 하위 설정 비활성화');
  await page.getByRole('switch', { name: '살균 활성화' }).check();
  await page.getByRole('combobox', { name: '살균 시간' }).selectOption('20');
  await page.getByRole('button', { name: '살균 시작' }).click();
  ok(await page.evaluate(() => SmartTrayApp.store.get().trays[0].effectUntil > Date.now()), '살균 미리보기');
  await page.getByRole('navigation', { name: '모바일 주 메뉴' }).getByRole('link', { name: '트레이', exact: true }).click();
  await page.waitForURL('**/#trays');
  ok((await page.locator('.tray-features > span:last-child').first().textContent()).trim() === '살균 ON', '살균 동작 중 ON 표시');
  await page.locator('button[data-route="detail"][data-id="1"]').click();
  await page.waitForURL('**/#detail/1');
  await page.reload();
  await page.waitForFunction(() => SmartTrayApp.store.get().connection === 'connected');
  ok(await page.getByRole('heading', { level: 1, name: '사원증', exact: true }).count() === 1, '별칭 새로고침 복원');
  ok(!await page.getByRole('switch', { name: 'LED 활성화', exact: true }).isChecked(), 'LED 설정 새로고침 복원');
  ok(await page.getByRole('combobox', { name: '살균 시간' }).inputValue() === '20', '살균 시간 새로고침 복원');
  await page.getByRole('navigation', { name: '모바일 주 메뉴' }).getByRole('link', { name: '기록', exact: true }).click();
  await page.waitForURL('**/#activity');
  await page.getByRole('button', { name: '알림', exact: true }).click();
  ok(await page.getByRole('heading', { name: '아직 기록된 활동이 없어요' }).count() === 1, '기록 필터 빈 상태');
  await page.getByRole('navigation', { name: '모바일 주 메뉴' }).getByRole('link', { name: '설정', exact: true }).click();
  await page.waitForURL('**/#settings');
  await page.locator('button[data-route="notifications"]').click();
  await page.waitForURL('**/#notifications');
  await page.getByRole('switch', { name: '사원증 알림', exact: true }).waitFor();
  ok(await page.getByRole('switch', { name: '사원증 알림', exact: true }).count() === 1, '알림 설정에 별칭 반영');
  await page.getByRole('switch', { name: '전체 알림', exact: true }).uncheck();
  ok(await page.getByRole('switch', { name: '현관문 열림 알림' }).isDisabled(), '전체 알림 비활성화 반영');
  await page.getByRole('switch', { name: '전체 알림', exact: true }).check();
  await page.getByRole('button', { name: '알림 미리보기', exact: true }).click();
  ok(await page.evaluate(() => SmartTrayApp.store.get().notifications[0].kind === 'preview'), '알림 미리보기 생성');
  ok(await page.locator('#notification-root .android-notification').count() === 1, '상단 Android 시스템 알림 카드');
  ok(!(await page.locator('main').innerText()).includes('앱 내부 알림'), '시스템 알림 미리보기 문구');
  await page.locator('#notification-root').getByRole('button', { name: '트레이 확인', exact: true }).click();
  await page.waitForURL('**/#trays');
  ok(await page.evaluate(() => SmartTrayApp.store.get().notifications[0].read), '묶음 알림 탭으로 트레이 목록 이동 및 읽음');
  await page.goBack();
  await page.waitForURL('**/#notifications');
  await page.getByRole('button', { name: '알림 미리보기', exact: true }).click();
  await page.getByRole('button', { name: '알림 닫기', exact: true }).click();
  ok(await page.locator('#notification-root .android-notification').count() === 0, '시스템 알림 배너 닫기');
  await page.getByRole('button', { name: '뒤로', exact: true }).click();
  await page.waitForURL('**/#settings');
  checks.push('앱 뒤로 가기');
  ok(await page.locator('.settings-link[data-action="developer"]').count() === 1, '개발 중 설정 화면에 개발자 진입 버튼 표시');
  await page.locator('.settings-link[data-action="developer"]').click();
  await page.getByRole('dialog').waitFor();
  await page.locator('[data-scenario="A"]').click();
  await page.waitForFunction(() => SmartTrayApp.store.get().notifications[0].kind === 'belongings');
  ok(await page.evaluate(() => SmartTrayApp.store.get().notifications[0].items.join(',') === '사원증,2번 트레이'), 'A UI: 남은 물건 묶음');
  const count = await page.evaluate(() => SmartTrayApp.store.get().notifications.length);
  await page.locator('[data-action="door-open"]').click();
  ok(await page.evaluate(() => SmartTrayApp.store.get().notifications.length) === count, '열린 문 재클릭 중복 방지');
  await page.locator('[data-scenario="B"]').click();
  await page.waitForFunction(() => SmartTrayApp.store.get().notifications[0].kind === 'door');
  ok(await page.evaluate(() => SmartTrayApp.store.get().notifications[0].items.length === 0 && !SmartTrayApp.store.get().preferences.trays[0].notification), 'B UI: 개별 알림 제외');
  await page.locator('[data-scenario="C"]').click();
  ok(await page.evaluate(() => SmartTrayApp.store.get().trays.every(t => !t.present)), 'C UI: 전체 빈 상태');
  await page.locator('[data-scenario="D"]').click();
  await page.waitForFunction(() => SmartTrayApp.store.get().connection === 'disconnected');
  if (await page.getByRole('button', { name: '알림 닫기', exact: true }).count()) await page.getByRole('button', { name: '알림 닫기', exact: true }).click();
  await page.getByRole('button', { name: '개발자 패널 닫기' }).click();
  await page.getByRole('navigation', { name: '모바일 주 메뉴' }).getByRole('link', { name: '홈', exact: true }).click();
  await page.waitForURL('**/#home');
  await page.getByText('마지막 수신 정보로는 현재 소지품 상태를 확인할 수 없어요.', { exact: true }).waitFor();
  ok((await page.locator('main').innerText()).includes('마지막 수신 정보로는 현재 소지품 상태를 확인할 수 없어요'), 'D UI: 과거 데이터 안내');
  await page.getByRole('button', { name: '알림함', exact: false }).click();
  await page.waitForURL('**/#inbox');
  await page.getByRole('button', { name: '모두 읽음' }).click();
  ok(await page.evaluate(() => SmartTrayApp.store.get().notifications.every(n => n.read)), '알림함 읽음 처리');
  await page.evaluate(() => SmartTrayApp.navigate('device'));
  await page.waitForURL('**/#device');
  await page.getByRole('button', { name: '다시 연결하기' }).click();
  await page.waitForFunction(() => SmartTrayApp.store.get().connection === 'connected');
  checks.push('장치 UI 재연결');
  return { passed: checks.length, checks };
};
